interface SquadPlayerSeed {
  id: string;
  name: string;
  englishName: string;
  nationalTeam: string;
  matchId: string;
  teamId: string;
  teamName: string;
  teamShort: string;
  teamColor: string;
  position: Position;
  backNumber: number;
  basePrice: number;
  currentPrice?: number;
  previousPrice?: number;
  eventText: string;
  sentiment?: EventSentiment;
  minute?: number;
  rating?: number;
  goals?: number;
  assists?: number;
  shotsOnTarget?: number;
  keyPasses?: number;
}

function createSquadPlayer(seed: SquadPlayerSeed): Player {
  const cfg = getTierConfig(seed.basePrice);
  const currentPrice = seed.currentPrice ?? Math.round((seed.basePrice * 1.03) / 10) * 10;
  const previousPrice = seed.previousPrice ?? Math.round((seed.basePrice * 1.015) / 10) * 10;
  const midPrice = Math.round(((seed.basePrice + previousPrice) / 2) / 10) * 10;
  return {
    id: seed.id,
    name: seed.name,
    englishName: seed.englishName,
    nationalTeam: seed.nationalTeam,
    matchId: seed.matchId,
    teamId: seed.teamId,
    teamName: seed.teamName,
    teamShort: seed.teamShort,
    teamColor: seed.teamColor,
    position: seed.position,
    backNumber: seed.backNumber,
    tier: cfg.tier,
    totalShares: cfg.totalShares,
    marketSupply: cfg.marketSupply,
    basePrice: seed.basePrice,
    initialPrice: seed.basePrice,
    currentPrice,
    previousPrice,
    priceHistory: [
      { timeLabel: "15'", price: seed.basePrice },
      { timeLabel: "30'", price: midPrice },
      { timeLabel: "45'", price: previousPrice },
      { timeLabel: "60'", price: previousPrice },
      { timeLabel: "현재", price: currentPrice },
    ],
    lastEvent: {
      text: seed.eventText,
      sentiment: seed.sentiment ?? "positive",
      minute: seed.minute ?? 55,
    },
    stats: {
      rating: seed.rating ?? 7.5,
      goals: seed.goals ?? 0,
      assists: seed.assists ?? 0,
      shotsOnTarget: seed.shotsOnTarget ?? 1,
      keyPasses: seed.keyPasses ?? 1,
    },
  };
}

